export function reviewedTopologyMediaBindings(scenes, bindings = TOPOLOGY_MEDIA_BINDINGS) {
  const acts = Object.keys(scenes);
  if (acts.length !== 12 || Object.keys(bindings).sort().join('|') !== [...acts].sort().join('|')) {
    throw new Error('Topology clips must match all twelve acts.');
  }
  if (acts.every(act => bindings[act] == null)) return null;
  const files = new Set();
  for (const act of acts) {
    const clip = bindings[act];
    if (!clip || typeof clip.file !== 'string' || !clip.file.startsWith(`assets/saga/${act}`) || !clip.file.endsWith('.mp4') ||
        typeof clip.poster !== 'string' || !clip.poster.startsWith('assets/saga/') ||
        !/^[a-f0-9]{64}$/.test(clip.sha256 || '') || !Number.isSafeInteger(clip.bytes) || clip.bytes <= 0 ||
        clip.frames !== 345 || clip.fps !== 24 || clip.duration !== scenes[act].duration ||
        clip.width !== 1344 || clip.height !== 768 || files.has(clip.file)) {
      throw new Error(`Actual reviewed topology media is required for ${act}.`);
    }
    files.add(clip.file);
  }
  return bindings;
}
